#!/usr/bin/env node
// Writes src/styles/fonts.css: an @font-face for every font PaperNotes ships
// (the bundled ones in src/core/fonts.js), Latin set only, straight from the
// Fontsource packages in node_modules. Vite copies each file into the build;
// a browser only downloads a face the first time a note uses it.
//
//   node scripts/gen-fonts.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUNDLED, VARIABLE, bundledFamily } from '../src/core/fonts.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/styles/fonts.css');

let css = `/* Generated by scripts/gen-fonts.mjs from src/core/fonts.js: edit those, not this.
   Open fonts from Fontsource (SIL Open Font License 1.1), Latin set only. */\n\n`;
let files = 0;
let bytes = 0;

for (const pkg of BUNDLED) {
  const variable = VARIABLE.has(pkg);
  const dir = path.join(ROOT, 'node_modules', variable ? '@fontsource-variable' : '@fontsource', pkg, 'files');
  if (!fs.existsSync(dir)) throw new Error(`missing font package for ${pkg}: npm install it first`);
  const have = new Set(fs.readdirSync(dir));
  const url = (f) => {
    files++;
    bytes += fs.statSync(path.join(dir, f)).size;
    return `url(${path.relative(path.dirname(OUT), path.join(dir, f)).split(path.sep).join('/')}) format('woff2')`;
  };
  const face = (style, weight, file) =>
    `@font-face {\n  font-family: '${bundledFamily(pkg)}';\n  font-style: ${style};\n  font-display: swap;\n  font-weight: ${weight};\n  src: ${url(file)};\n}\n`;
  if (variable) {
    for (const style of ['normal', 'italic']) {
      const axis = ['wght', 'standard'].find((a) => have.has(`${pkg}-latin-${a}-${style}.woff2`));
      if (axis) css += face(style, '100 900', `${pkg}-latin-${axis}-${style}.woff2`);
    }
  } else {
    for (const weight of [400, 700]) {
      for (const style of ['normal', 'italic']) {
        const f = `${pkg}-latin-${weight}-${style}.woff2`;
        if (have.has(f)) css += face(style, weight, f);
      }
    }
  }
}

fs.writeFileSync(OUT, css);

// The fonts' own notices, for Settings → Licenses: each font's copyright
// lines, then the SIL Open Font License once (every one of them uses it).
let notices = '';
let ofl = '';
for (const pkg of BUNDLED) {
  const dir = path.join(ROOT, 'node_modules', VARIABLE.has(pkg) ? '@fontsource-variable' : '@fontsource', pkg);
  const text = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n');
  const cut = text.indexOf('This Font Software is licensed');
  if (cut < 0) throw new Error(`${pkg}: not the SIL OFL? check its LICENSE`);
  notices += `- **${bundledFamily(pkg).replace(/^PN /, '')}**: ${text.slice(0, cut).trim().replace(/\s*\n\s*/g, ' ')}\n`;
  if (!ofl) ofl = text.slice(text.indexOf('-----', cut)).trim();
}
fs.writeFileSync(path.join(ROOT, 'src/assets/font-licenses.md'),
  `<!-- Generated by scripts/gen-fonts.mjs. -->\nThese fonts ship with PaperNotes (the Latin set of each, from [Fontsource](https://fontsource.org)). Each is licensed under the SIL Open Font License, Version 1.1, printed below.\n\n${notices}\n\`\`\`text\n${ofl}\n\`\`\`\n`);
console.log(`wrote ${BUNDLED.length} families, ${files} files, ${(bytes / 1048576).toFixed(2)} MB`);
